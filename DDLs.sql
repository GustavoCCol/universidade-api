CREATE TABLE ALUNO (
ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
NOME VARCHAR2(200) NOT NULL,
MATRICULA VARCHAR2(14) NOT NULL, 
DATA_NASCIMENTO DATE NOT NULL, 
DATA_INGRESSO DATE NOT NULL, 
CURSO VARCHAR2(50));

CREATE TABLE MATERIA (
ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
PROFESSOR VARCHAR2(100), 
NOME VARCHAR2(200));

CREATE TABLE ALUNO_MATERIA (
ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
MATERIA_ID NUMBER, 
ALUNO_ID NUMBER, 
CONSTRAINT FK_MATERIA_ID FOREIGN KEY (MATERIA_ID) REFERENCES MATERIA(ID), 
CONSTRAINT FK_ALUNO_ID FOREIGN KEY (ALUNO_ID) REFERENCES ALUNO(ID));

CREATE TABLE NOTA (
ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
MATERIA_ID NUMBER, 
ALUNO_ID NUMBER, 
BIMESTRE NUMBER NOT NULL, 
NOTA FLOAT(4) NOT NULL, 
CONSTRAINT FK_MATERIA_ID_NOTA FOREIGN KEY (MATERIA_ID) REFERENCES MATERIA(ID), 
CONSTRAINT FK_ALUNO_ID_NOTA FOREIGN KEY (ALUNO_ID) REFERENCES ALUNO(ID));